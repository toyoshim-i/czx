#!/usr/bin/env python3
"""Generate src/video/font_jp_data.cpp from Misaki Gothic 2nd BDF + CP932 table."""

from __future__ import annotations

import argparse
import io
import os
import sys
import urllib.request
import zipfile

MISAKI_URL = "https://littlelimit.net/arc/misaki/misaki_bdf_2021-05-05.zip"
BDF_MEMBER = "misaki_gothic_2nd.bdf"
FONT_ASCENT = 7


def fetch_zip_bytes(zip_path: str | None) -> bytes:
    if zip_path:
        with open(zip_path, "rb") as f:
            return f.read()
    with urllib.request.urlopen(MISAKI_URL, timeout=30) as resp:
        return resp.read()


def parse_misaki_bdf(bdf_text: str) -> list[tuple[int, bool, list[int]]]:
    glyphs: list[tuple[int, bool, list[int]]] = []
    cp: int | None = None
    dw = 8
    bbx = (0, 0, 0, 0)
    in_bm = False
    raw_rows: list[int] = []
    in_char = False

    for line in bdf_text.splitlines():
        if line.startswith("STARTCHAR "):
            in_char = True
            cp = None
            dw = 8
            bbx = (0, 0, 0, 0)
            in_bm = False
            raw_rows = []
        elif not in_char:
            continue
        elif line.startswith("ENCODING "):
            cp = int(line.split()[1])
        elif line.startswith("DWIDTH "):
            dw = int(line.split()[1])
        elif line.startswith("BBX "):
            parts = line.split()
            bbx = (int(parts[1]), int(parts[2]), int(parts[3]), int(parts[4]))
        elif line == "BITMAP":
            in_bm = True
        elif line == "ENDCHAR":
            if cp is not None and 0x80 <= cp <= 0xFFFF:
                w, h, xoff, yoff = bbx
                norm = [0] * 8
                top = FONT_ASCENT - (yoff + h)
                for i in range(min(h, len(raw_rows))):
                    r = top + i
                    if 0 <= r < 8:
                        val = raw_rows[i]
                        if xoff >= 0:
                            val = (val >> xoff) & 0xFF
                        else:
                            val = (val << (-xoff)) & 0xFF
                        norm[r] = val
                glyphs.append((cp, dw <= 4, norm))
            in_char = False
            in_bm = False
        elif in_bm:
            s = line.strip()
            if s:
                raw_rows.append(int(s[:2], 16))

    glyphs.sort(key=lambda g: g[0])
    # Deduplicate if any codepoint appears twice (keep last)
    dedup: dict[int, tuple[int, bool, list[int]]] = {}
    for g in glyphs:
        dedup[g[0]] = g
    return [dedup[k] for k in sorted(dedup)]


def build_cp932_table() -> list[int]:
    leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
    trails = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))
    assert len(leads) == 60
    assert len(trails) == 188
    table: list[int] = []
    for b1 in leads:
        for b2 in trails:
            try:
                ch = bytes([b1, b2]).decode("cp932")
                if len(ch) == 1 and ord(ch) <= 0xFFFF:
                    table.append(ord(ch))
                else:
                    table.append(0)
            except UnicodeDecodeError:
                table.append(0)
    return table


def generate_cpp(glyphs: list[tuple[int, bool, list[int]]], cp932: list[int]) -> str:
    n = len(glyphs)
    hw_bytes = [0] * ((n + 7) // 8)
    for i, (_, half_w, _) in enumerate(glyphs):
        if half_w:
            hw_bytes[i >> 3] |= 1 << (i & 7)

    out: list[str] = []
    out.append(
        """// Generated by scripts/gen-jp-font.py from Misaki Gothic 2nd (misaki_bdf_2021-05-05.zip).
//
// Misaki Font (美咲フォント) 2021-05-05
// Copyright (C) 2002-2021 Num Kadoma
//
// These fonts are free software. Unlimited permission is granted to use,
// copy, and distribute them, with or without modification, either
// commercially or noncommercially. THESE FONTS ARE PROVIDED "AS IS"
// WITHOUT WARRANTY.

#include "video/font_jp.hpp"

namespace czx::video {
"""
    )
    out.append(f"const size_t kMisakiGlyphCount = {n}u;\n")

    out.append("const uint16_t kMisakiCodepoints[] = {")
    for i in range(0, n, 12):
        chunk = ", ".join(f"0x{g[0]:04X}" for g in glyphs[i : i + 12])
        out.append(f"    {chunk},")
    out.append("};\n")

    out.append("const uint8_t kMisakiGlyphs[][8] = {")
    for cp, _, rows in glyphs:
        hexs = ", ".join(f"0x{b:02X}" for b in rows)
        out.append(f"    {{{hexs}}}, // U+{cp:04X}")
    out.append("};\n")

    out.append("const uint8_t kMisakiHalfWidth[] = {")
    for i in range(0, len(hw_bytes), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in hw_bytes[i : i + 16])
        out.append(f"    {chunk},")
    out.append("};\n")

    out.append(f"const uint16_t kCp932ToUnicode[{len(cp932)}] = {{")
    for i in range(0, len(cp932), 16):
        chunk = ", ".join(f"0x{v:04X}" for v in cp932[i : i + 16])
        out.append(f"    {chunk},")
    out.append("};\n")
    out.append("}  // namespace czx::video\n")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--zip", help="Local path to misaki_bdf_2021-05-05.zip", default=None)
    parser.add_argument(
        "--out",
        default=os.path.join(os.path.dirname(__file__), "..", "src", "video", "font_jp_data.cpp"),
    )
    args = parser.parse_args()

    zip_bytes = fetch_zip_bytes(args.zip)
    with zipfile.ZipFile(io.BytesIO(zip_bytes)) as zf:
        bdf_text = zf.read(BDF_MEMBER).decode("ascii", errors="replace")

    glyphs = parse_misaki_bdf(bdf_text)
    cp932 = build_cp932_table()
    cpp = generate_cpp(glyphs, cp932)

    out_path = os.path.abspath(args.out)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(cpp)

    print(f"Generated {out_path}: {len(glyphs)} glyphs, {len(cp932)} CP932 entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
